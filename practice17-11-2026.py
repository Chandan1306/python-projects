marks = [10,20,30,40,50] #initializing the list
print(marks[0]) #prints the first element of the list
print(marks[-1]) #prints the last element of the list
print(marks[-2]) #prints the second last element of the list
print(marks[1:4]) #prints the elements from index 1 to 3 (4 is exclusive)
print(marks[0:3]) #prints the elements from index 0 to 2 (3 is exclusive)